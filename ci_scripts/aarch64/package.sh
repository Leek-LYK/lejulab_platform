#!/bin/bash
# 从 staging/installed/ 出发，整理出最终下游仓库目录树
# 流程: 清理头文件/cmake config / strip 符号 / 拷 3rd_party / 拷明文 / 写 setup.bash/VERSION/README / sanity

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(realpath "$SCRIPT_DIR/../..")"
cd "$PROJECT_DIR"

STAGING="$PROJECT_DIR/staging"
INSTALLED="$STAGING/installed"

[ -d "$INSTALLED" ] || { echo "[package] ERROR: $INSTALLED missing — run build.sh first"; exit 1; }

# ============================================================
# 1. 清理不需要随车发布的 install 产物
#    cmake --install 可能产出 include/, lib/cmake/, share/<pkg>/, .a 等
#    全部删除（我们用自己的 src/<pkg>/config 替代 share）
# ============================================================
echo "[package 1/8] purging private headers / cmake configs / static libs..."
rm -rf "$INSTALLED/lib/cmake"
rm -rf "$INSTALLED/lib/pkgconfig"
# share/ 下默认产物（leju_launch 装的 launch/config）我们改从源码 cp，
# 因此这里删 share/ 防止重复
rm -rf "$INSTALLED/share"
# 删除静态库
find "$INSTALLED" -name "*.a" -type f \
    ! -name 'liblejusdk-dds-idl.a' \
    ! -name 'liblejusdk-dds-rpc.a' \
    -delete 2>/dev/null || true
if [ -d "$INSTALLED/include" ]; then
    find "$INSTALLED/include" -mindepth 1 -maxdepth 1 \
        ! -name 'lejusdk-lowlevel' ! -name 'lejusdk-vr' \
        ! -name 'lejusdk-dds-idl' ! -name 'lejusdk-topic-pubsub' \
        ! -name 'dds_rpc' ! -name 'rpc_idl' \
        -exec rm -rf {} + 2>/dev/null || true
fi

# ============================================================
# 2. strip 符号
# ============================================================
STRIP="$(which aarch64-linux-gnu-strip 2>/dev/null || echo strip)"
echo "[package 2/8] stripping symbols (using $STRIP)..."
# 库: 保留动态符号表
while IFS= read -r so; do
    [ -L "$so" ] && continue
    if file "$so" 2>/dev/null | grep -q "ELF"; then
        $STRIP --strip-unneeded "$so" 2>/dev/null || \
            echo "[package] WARN: strip failed on $so"
    fi
done < <(find "$INSTALLED/lib" -name "*.so*" -type f 2>/dev/null || true)

# 可执行: 彻底 strip
while IFS= read -r exe; do
    if file "$exe" 2>/dev/null | grep -q "ELF.*executable"; then
        $STRIP --strip-all "$exe" 2>/dev/null || \
            echo "[package] WARN: strip failed on $exe"
    fi
done < <(find "$INSTALLED/bin" -type f 2>/dev/null || true)

# ============================================================
# 3. 拷 3rd_party 预编译 .so（cyclonedds、iceoryx 等）
#    glob 所有 aarch64 子目录的 lib/*.so*，含 SONAME 软链
# ============================================================
echo "[package 3/8] copying 3rd_party .so libs..."
shopt -s nullglob
for sof in "$PROJECT_DIR"/src/lejusdk/3rd_party/aarch64/*/lib/*.so*; do
    cp -a "$sof" "$INSTALLED/lib/" 2>/dev/null || true
done
shopt -u nullglob

# MuJoCo 是 binary 包的运行时依赖，随 installed 一并发布。
MUJOCO_LIB_DIR="$PROJECT_DIR/src/leju-mujoco-sim/3rd_party/aarch64/mujoco-3.2.0/lib"
for sof in "$MUJOCO_LIB_DIR"/libmujoco.so*; do
    [ -e "$sof" ] || continue
    cp -a "$sof" "$INSTALLED/lib/"
done

# ============================================================
# 4. 生成 installed/setup.bash
# ============================================================
echo "[package 4/8] generating setup.bash..."
cat > "$INSTALLED/setup.bash" <<'SETUP_EOF'
#!/bin/bash
# Auto-generated by lejulab-platform CI (aarch64 release)
# 用法: source installed/setup.bash
_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export LD_LIBRARY_PATH="$_DIR/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export PATH="$_DIR/bin${PATH:+:$PATH}"
export LEJULAB_INSTALL_ROOT="$_DIR"
export LEJULAB_PROJECT_ROOT="$(cd "$_DIR/.." && pwd)"
if [ -z "${ROBOT_VERSION:-}" ]; then
    echo "[lejulab] 请 export ROBOT_VERSION=<14|46|52> 后再 launch" >&2
fi
SETUP_EOF
chmod +x "$INSTALLED/setup.bash"

# ============================================================
# 5. 拷明文资源（scripts、docs、launch、config、assets）
# ============================================================
echo "[package 5/8] copying plaintext resources..."

# scripts (Python / Shell)
if [ -d "$PROJECT_DIR/scripts" ]; then
    cp -r "$PROJECT_DIR/scripts" "$STAGING/"
    # 清理 __pycache__ / logs / 临时产物
    find "$STAGING/scripts" -name "__pycache__" -type d -exec rm -rf {} + 2>/dev/null || true
    find "$STAGING/scripts" -name "*.pyc" -type f -delete 2>/dev/null || true
    rm -rf "$STAGING/scripts/logs" 2>/dev/null || true
fi

# docs/ —— 黑名单方式过滤掉内部文档
if [ -d "$PROJECT_DIR/docs" ]; then
    cp -r "$PROJECT_DIR/docs" "$STAGING/"
    # 内部设计/计划/报告/迁移进度，不对外
    rm -rf "$STAGING/docs/plans"
    rm -rf "$STAGING/docs/reports"
    rm -rf "$STAGING/docs/superpowers"
    rm -f  "$STAGING/docs/rk3588-migration-progress.md"
    rm -f  "$STAGING/docs/cross-machine-rl-mujoco-guide.md"
fi

# src/ 下保留路径的资源
mkdir -p "$STAGING/src"
for pkg in leju_assets leju_launch; do
    if [ -d "$PROJECT_DIR/src/$pkg" ]; then
        cp -r "$PROJECT_DIR/src/$pkg" "$STAGING/src/"
        # 进入后清理 C++ / CMake
        find "$STAGING/src/$pkg" \
            \( -name "*.cpp" -o -name "*.hpp" -o -name "*.h" -o -name "*.c" \
               -o -name "CMakeLists.txt" -o -name "*.cmake" -o -name "*.a" \) \
            -type f -delete 2>/dev/null || true
        # 清空因删文件而剩下的空目录（不强求，保留也无害）
    fi
done

# leju-hardware 的 config 单独保留
if [ -d "$PROJECT_DIR/src/leju-hardware/config" ]; then
    mkdir -p "$STAGING/src/leju-hardware"
    cp -r "$PROJECT_DIR/src/leju-hardware/config" "$STAGING/src/leju-hardware/"
fi

# 各 controller 的 config（不拷代码）
for pkg in leju-rl-controller leju-dummy-controller leju-keyboard-controller; do
    src_cfg="$PROJECT_DIR/src/leju-controllers/$pkg/config"
    if [ -d "$src_cfg" ]; then
        mkdir -p "$STAGING/src/leju-controllers/$pkg"
        cp -r "$src_cfg" "$STAGING/src/leju-controllers/$pkg/"
    fi
done

# ============================================================
# 5.5 脱敏：把内网 IP（192.168.50.*）替换成占位符
#     只处理文本文件，跳过 .png/.jpg/.onnx 等二进制
# ============================================================
echo "[package 5.5/8] scrubbing internal IPs (192.168.50.*) -> <YOUR_HOST_IP>..."
find "$STAGING" -type f \
    ! -name "*.png" ! -name "*.jpg" ! -name "*.jpeg" ! -name "*.svg" \
    ! -name "*.onnx" ! -name "*.so*" ! -name "*.a" \
    ! -name "*.urdf" ! -name "*.xacro" ! -name "*.stl" ! -name "*.dae" \
    ! -path "$STAGING/installed/bin/*" \
    -exec grep -lE "192\.168\.50\.[0-9x]+" {} \; 2>/dev/null \
    | while read -r f; do
        sed -i 's/192\.168\.50\.[0-9x]\+/<YOUR_HOST_IP>/g' "$f"
        echo "  scrubbed: ${f#$STAGING/}"
    done

# ============================================================
# 6. 生成 VERSION 文件
# ============================================================
echo "[package 6/8] writing VERSION..."
cd "$PROJECT_DIR"
UPSTREAM_SHA="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
UPSTREAM_DESCRIBE="$(git describe --tags --always --dirty 2>/dev/null || echo unknown)"
BUILD_ID="$(date -u +%Y%m%d).$(printf '%03d' "${CI_PIPELINE_IID:-0}")"
BUILD_TIME="$(date -u -Iseconds)"

cat > "$STAGING/VERSION" <<EOF
upstream-commit: $UPSTREAM_SHA
upstream-describe: $UPSTREAM_DESCRIBE
build-id: $BUILD_ID
build-time: $BUILD_TIME
EOF

# ============================================================
# 7. 生成 README_DEPLOY.md + MANIFEST.txt
# ============================================================
echo "[package 7/8] writing README + MANIFEST..."

ls "$INSTALLED/bin" 2>/dev/null | sort > "$INSTALLED/MANIFEST.txt"
if [ -d "$INSTALLED/bin/tests" ]; then
    {
        echo
        echo "# Tests"
        ls "$INSTALLED/bin/tests" | sed 's|^|tests/|'
    } >> "$INSTALLED/MANIFEST.txt"
fi

cat > "$STAGING/README_DEPLOY.md" <<'README_EOF'
# lejulab-platform aarch64 release

预编译产物，开箱即用。**不包含** C++ 源码、头文件或 CMake 配置。

## 部署

```bash
# 1. clone 本仓库到板子
git clone <this-repo-url>
cd <repo-name>

# 2. 注入环境
source installed/setup.bash

# 3. 设定机器人版本
export ROBOT_VERSION=46    # 14=Roban2 base, 46=Kuavo 4 UAE, 52=Kuavo 5 base

# 4. 启动
sudo -E bash src/leju_launch/scripts/launch_real.sh
```

`sudo -E` 透传环境变量（`LD_LIBRARY_PATH` / `PATH` / `ROBOT_VERSION`）。

## 目录说明

| 目录 | 内容 |
|---|---|
| `installed/bin/` | 业务可执行（hardware_node、run_rl_controller 等） |
| `installed/bin/tests/` | 测试二进制（需要手动调） |
| `installed/lib/` | 动态库（SDK + 3rd_party） |
| `installed/setup.bash` | 环境注入脚本 |
| `installed/MANIFEST.txt` | 本次发布的可执行清单 |
| `scripts/` | Python/Shell 工具（诊断、CAN 调参、分析等） |
| `src/leju_launch/` | launch 与启动脚本 |
| `src/leju_assets/` | URDF / MJCF 资产 |
| `src/leju-hardware/config/` | 硬件配置（kuavo.json） |
| `src/leju-controllers/*/config/` | 控制器配置 + ONNX 模型 |
| `docs/` | 文档 |
| `VERSION` | 本次发布的版本信息 |

## 调试

- 看可执行链接是否正常：`ldd installed/bin/hardware_node`
- 看动态符号：`nm -D installed/lib/lib<x>.so | head`
- 诊断脚本：`sudo bash scripts/diagnostics/check_all.sh`
README_EOF

# ============================================================
# 8. sanity 检查
# ============================================================
echo "[package 8/8] running sanity checks..."
bash "$SCRIPT_DIR/sanity.sh" "$STAGING"

echo
echo "[package] DONE. staging tree:"
du -sh "$STAGING"/* 2>/dev/null || true
